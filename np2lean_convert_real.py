def lean_ok(goal: str, tactic: str, imports: List[str], timeout: float) -> Tuple[bool, str]:
    lines = []
    for m in imports:
        lines.append(f"import {m}")
    lines += [
        "",
        "set_option maxHeartbeats 400000",
        "set_option linter.unusedVariables false",
        f"example : {goal} := by",
        f"  {tactic}",
        "",
    ]
    code = "\n".join(lines)
    with tempfile.TemporaryDirectory() as td:
        src = os.path.join(td, "Check.lean")
        with open(src, "w", encoding="utf-8") as f:
            f.write(code)
        try:
            r = subprocess.run(["lean", src], capture_output=True, text=True, timeout=timeout)
            return (r.returncode == 0, (r.stderr or "").strip())
        except subprocess.TimeoutExpired:
            return (False, f"timeout>{timeout}s")

def try_convert(rec: Dict[str, Any], allow_mathlib: bool, timeout: float) -> Optional[Dict[str, Any]]:

    texts = []
    for k in ("text", "target", "title"):
        if k in rec and rec[k]:
            texts.append(norm(str(rec[k])))

    for s in texts:
        for det in DETECTORS:
            goal, tac, imps = (None, None, None)
            out = det(s)
            if not out:
                continue
            goal, tac, imps = out
            if not allow_mathlib:
                imps = [m for m in imps if m != "Mathlib"]
            ok, _ = lean_ok(goal, tac, imps, timeout)
            if ok:
                return {
                    "id": rec.get("id", None),
                    "goal": goal,
                    "gold_tactic": tac,
                    "imports": imps
                }
    return None

def convert_split(records, allow_mathlib: bool, timeout: float) -> Tuple[Dataset, Dict[str,int]]:
    kept, skipped = 0, 0
    out: List[Dict[str, Any]] = []
    for rec in records:
        conv = try_convert(rec, allow_mathlib=allow_mathlib, timeout=timeout)
        if conv:
            out.append(conv)
            kept += 1
        else:
            skipped += 1
    stats = {"kept": kept, "skipped": skipped}
    return Dataset.from_list(out) if out else Dataset.from_list([]), stats

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--np_root", required=True, help="hf dataset path for naturalproofs (load_from_disk)")
    ap.add_argument("--out_root", required=True, help="output path for converted, verified dataset")
    ap.add_argument("--timeout", type=float, default=6.0, help="lean timeout per example in seconds")
    ap.add_argument("--seed", type=int, default=0, help="rng seed")
    ap.add_argument("--no_mathlib", action="store_true", help="disable Mathlib import; use Std only")
    args = ap.parse_args()

    random.seed(args.seed)
    allow_mathlib = not args.no_mathlib

    ds_src = load_from_disk(args.np_root)
    splits: Dict[str, Dataset] = {}
    stats: Dict[str, Dict[str,int]] = {}

    for sp in ["train", "validation", "test"]:
        if sp not in ds_src: continue
        print(f"[split] {sp} rows={len(ds_src[sp])}")
        ds_out, s = convert_split(ds_src[sp], allow_mathlib=allow_mathlib, timeout=args.timeout)
        splits[sp] = ds_out
        stats[sp] = s


    splits = {k: v for k, v in splits.items() if len(v) > 0}
    if not splits:
        raise SystemExit("no convertible examples were found; check mathlib availability or widen detectors")

    out = DatasetDict(splits)
    os.makedirs(args.out_root, exist_ok=True)
    out.save_to_disk(args.out_root)

    report = {"splits": stats, "out_root": args.out_root, "mathlib": allow_mathlib}
    with open(os.path.join(args.out_root, "conversion_report.json"), "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)
    print(json.dumps(report, indent=2))

if __name__ == "__main__":
    main()