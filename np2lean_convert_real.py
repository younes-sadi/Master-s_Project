def det_comp_id(s: str) -> Optional[Tuple[str, str, List[str]]]:
    # (f ∘ id) x = f x
    if re.search(r"\b∘\b|\bcomposition\b", s):
        goal = "∀ (α β : Type) (f : α → β) (x : α), (f ∘ id) x = f x"
        tactic = "intro α; intro β; intro f; intro x; rfl"
        return goal, tactic, ["Std", "Mathlib"]
    return None

