def det_add_zero_nat(s: str) -> Optional[Tuple[str, str, List[str]]]:
    # a + 0 = a or 0 + a = a
    if re.search(r"\b([a-zA-Z])\s*\+\s*0\s*=\s*\1\b", s):
        return "∀ a : Nat, a + 0 = a", "intro a; simp", ["Std"]
